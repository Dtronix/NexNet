using System.Reflection;
using System.Text;
using System.Text.Json;
using NexNet.Diagnostics;

#pragma warning disable VSTHRD200

namespace NexNet.IntegrationTests.Metrics;

/// <summary>
/// Exports the snapshot record field names to tests/golden/snapshot-fields.json, which the Java and JavaScript clients
/// check their snapshots against. The file is written when it is missing or NEXNET_UPDATE_GOLDEN=1; otherwise the test
/// fails when the records and the file disagree.
/// </summary>
internal class SnapshotFieldsExportTests
{
    private static readonly Type[] Records =
    [
        typeof(NexusSessionSnapshot),
        typeof(NexusBudgetSnapshot),
        typeof(NexusInvocationSnapshot),
        typeof(NexusPipeSnapshot),
        typeof(NexusPartialItemSnapshot),
        typeof(NexusLargeMessageSnapshot),
    ];

    [Test]
    public async Task SnapshotFields_MatchGoldenFile()
    {
        var expected = Render();
        var path = Path.Combine(FindRepositoryRoot(), "tests", "golden", "snapshot-fields.json");

        if (!File.Exists(path) || Environment.GetEnvironmentVariable("NEXNET_UPDATE_GOLDEN") == "1")
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            await File.WriteAllTextAsync(path, expected);
        }

        var actual = (await File.ReadAllTextAsync(path)).Replace("\r\n", "\n");
        await Assert.That(actual).IsEqualTo(expected);
    }

    /// <summary>
    /// The public instance properties of each record in declaration order, camelCased.
    /// </summary>
    private static string Render()
    {
        using var stream = new MemoryStream();
        using (var writer = new Utf8JsonWriter(stream, new JsonWriterOptions { Indented = true, NewLine = "\n" }))
        {
            writer.WriteStartObject();
            writer.WriteString("description",
                "Field names of the C# snapshot records (NexNet.Diagnostics), camelCased, in declaration order. "
                + "Generated by NexNet.IntegrationTests SnapshotFieldsExportTests; regenerate with NEXNET_UPDATE_GOLDEN=1.");
            writer.WriteStartObject("records");
            foreach (var record in Records)
            {
                writer.WriteStartArray(record.Name);
                foreach (var property in record.GetProperties(BindingFlags.Public | BindingFlags.Instance)
                             .OrderBy(p => p.MetadataToken))
                {
                    writer.WriteStringValue(JsonNamingPolicy.CamelCase.ConvertName(property.Name));
                }
                writer.WriteEndArray();
            }
            writer.WriteEndObject();
            writer.WriteEndObject();
        }

        return Encoding.UTF8.GetString(stream.ToArray()) + "\n";
    }

    private static string FindRepositoryRoot()
    {
        for (var dir = new DirectoryInfo(AppContext.BaseDirectory); dir != null; dir = dir.Parent)
        {
            if (File.Exists(Path.Combine(dir.FullName, "src", "NexNet.slnx")))
                return dir.FullName;
        }

        throw new InvalidOperationException("Repository root (src/NexNet.slnx) not found above " + AppContext.BaseDirectory);
    }
}
