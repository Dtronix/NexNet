using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using NexNet.Generator.Bundle;
using NexNet.Generator.Ir;
using NexNet.Generator.Targets;
using static NexNet.Generator.Tests.Bundle.BundleTestRunner;

namespace NexNet.Generator.Tests.Bundle;

/// <summary>The target bundle format (G04) and when the generator emits it.</summary>
public class TargetBundleTests
{
    // Non-ASCII content: two Latin-1 letters and a character outside the BMP.
    private static readonly string NonAscii = char.ConvertFromUtf32(0xFC) + char.ConvertFromUtf32(0xDF) + char.ConvertFromUtf32(0x1F680);

    private static readonly GeneratedFile[] SampleFiles =
    {
        new("java/com/acme/ChatServerProxy.java", "package com.acme;\n\npublic final class ChatServerProxy {}\n"),
        new("java/com/acme/Empty.java", ""),
        new("javascript/chat-server-proxy.js", "// " + NonAscii + "\n" + new string('x', 1000) + "\n"),
        new(TargetBundle.IrFileName, "{\n  \"irVersion\": 1\n}\n"),
    };

    // ------------------------------------------------------------------ format

    [Test]
    public async Task RoundTrip_PreservesPathsContentAndOrder()
    {
        var read = TargetBundle.Read(TargetBundle.Write(SampleFiles));

        await Assert.That(read.Count).IsEqualTo(SampleFiles.Length);
        for (var i = 0; i < SampleFiles.Length; i++)
            await Assert.That(read[i]).IsEqualTo(SampleFiles[i]);
    }

    [Test]
    public async Task Write_IsCommentOnlyAndCompilesToNothing()
    {
        var text = TargetBundle.Write(SampleFiles);
        var lines = text.Split('\n');

        await Assert.That(lines[0]).IsEqualTo("// <auto-generated/> NexNet target bundle v1");
        await Assert.That(text.EndsWith('\n')).IsTrue();
        await Assert.That(text.Contains('\r')).IsFalse();
        await Assert.That(lines.Where(l => l.Length > 0).All(l => l.StartsWith("// ", StringComparison.Ordinal))).IsTrue();
        await Assert.That(lines.Where(l => !l.StartsWith("// @file", StringComparison.Ordinal)).Max(l => l.Length))
            .IsLessThanOrEqualTo(TargetBundle.LineLength + 3);

        var tree = CSharpSyntaxTree.ParseText(text);
        await Assert.That(tree.GetRoot().DescendantNodes().Any()).IsFalse();
    }

    [Test]
    public async Task Write_HeaderCarriesSha256OfUtf8Content()
    {
        var text = TargetBundle.Write(new[] { new GeneratedFile("java/A.java", "abc") });

        // sha256("abc")
        await Assert.That(text).Contains("// @file java/A.java sha256=ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad\n");
        await Assert.That(text).Contains("// YWJj\n");
    }

    [Test]
    public async Task Write_IsDeterministic()
    {
        await Assert.That(TargetBundle.Write(SampleFiles)).IsEqualTo(TargetBundle.Write(SampleFiles.ToArray()));
    }

    [Test]
    public async Task Read_AcceptsCrLf()
    {
        var read = TargetBundle.Read(TargetBundle.Write(SampleFiles).Replace("\n", "\r\n"));
        await Assert.That(read.Count).IsEqualTo(SampleFiles.Length);
        await Assert.That(read[2]).IsEqualTo(SampleFiles[2]);
    }

    [Test]
    public async Task Read_RejectsAHashMismatch()
    {
        var text = TargetBundle.Write(new[] { new GeneratedFile("java/A.java", "abc") }).Replace("// YWJj", "// YWJk");
        await Assert.That(() => TargetBundle.Read(text)).ThrowsExactly<FormatException>();
    }

    [Test]
    public async Task Read_RejectsAnotherVersion()
    {
        var text = TargetBundle.Write(SampleFiles).Replace("bundle v1", "bundle v2");
        await Assert.That(() => TargetBundle.Read(text)).ThrowsExactly<FormatException>();
    }

    [Test]
    [Arguments("")]
    [Arguments("/java/A.java")]
    [Arguments("C:/A.java")]
    [Arguments("java\\A.java")]
    [Arguments("java//A.java")]
    [Arguments("java/../A.java")]
    [Arguments("java/./A.java")]
    [Arguments("java/A.java ")]
    public async Task Write_RejectsInvalidPaths(string path)
    {
        await Assert.That(() => TargetBundle.Write(new[] { new GeneratedFile(path, "x") })).ThrowsExactly<ArgumentException>();
    }

    [Test]
    public async Task Write_RejectsPathsThatDifferOnlyInCase()
    {
        await Assert.That(() => TargetBundle.Write(new[] { new GeneratedFile("java/A.java", "x"), new GeneratedFile("java/a.java", "y") }))
            .ThrowsExactly<ArgumentException>();
    }

    // ------------------------------------------------------------------ generator

    [Test]
    public async Task NoTargetConfigured_NoBundle()
    {
        var run = Run(new Dictionary<string, string>());

        await Assert.That(run.Bundle).IsNull();
        await Assert.That(run.Diagnostics.Select(d => d.Id).Distinct().ToArray()).IsEquivalentTo(new[] { "NEXNET044" });
    }

    [Test]
    public async Task Configured_BundleCarriesTheIr()
    {
        var run = Run(Configured());

        await Assert.That(run.Diagnostics).IsEmpty();
        await Assert.That(run.Bundle).IsNotNull();

        var files = TargetBundle.Read(run.Bundle!);
        var ir = files.Single(f => f.Path == TargetBundle.IrFileName);
        await Assert.That(IrJson.Read(ir.Content).Exports.Single().Name).IsEqualTo("ServerNexus");

        // Every other file is under a configured target's directory.
        await Assert.That(files.Where(f => f.Path != TargetBundle.IrFileName)
            .All(f => f.Path.StartsWith("java/", StringComparison.Ordinal) || f.Path.StartsWith("javascript/", StringComparison.Ordinal))).IsTrue();
    }

    [Test]
    public async Task ConfiguredWithoutExports_EmptyBundle()
    {
        var run = Run(Configured(), Source.Replace(", Targets = NexusTargets.Java | NexusTargets.JavaScript", ""));

        await Assert.That(run.Diagnostics).IsEmpty();
        await Assert.That(run.Bundle).IsNotNull();
        await Assert.That(TargetBundle.Read(run.Bundle!)).IsEmpty();
    }

    [Test]
    public async Task DesignTimeBuild_ValidatesButEmitsNoBundle()
    {
        var options = Configured(designTime: true);
        options.Remove("build_property.NexNetTarget_java_Package");
        var run = Run(options);

        await Assert.That(run.Bundle).IsNull();
        await Assert.That(run.Diagnostics.Select(d => d.Id).ToArray()).Contains("NEXNET045");

        var clean = Run(Configured(designTime: true));
        await Assert.That(clean.Bundle).IsNull();
        await Assert.That(clean.Diagnostics).IsEmpty();
    }

    [Test]
    public async Task TargetError_EmitsNoBundle()
    {
        var options = Configured();
        options.Remove("build_property.NexNetTarget_java_Package");
        var run = Run(options);

        await Assert.That(run.Diagnostics.Select(d => d.Id).ToArray()).Contains("NEXNET045");
        await Assert.That(run.Bundle).IsNull();
    }

    [Test]
    public async Task UnrelatedEdit_BundleStepIsCached()
    {
        var first = Run(Configured());
        var edited = first.Compilation.AddSyntaxTrees(CSharpSyntaxTree.ParseText(
            "namespace Demo; public class Unrelated { public int Value; }",
            new CSharpParseOptions(LanguageVersion.CSharp13)));
        var second = Rerun(first.Driver, edited);

        var step = second.Result.Results.Single().TrackedSteps[NexusGenerator.BundleTrackingName].Single();
        await Assert.That(step.Outputs.Single().Reason is IncrementalStepRunReason.Cached or IncrementalStepRunReason.Unchanged).IsTrue();
        await Assert.That(second.Bundle).IsEqualTo(first.Bundle);
    }
}
