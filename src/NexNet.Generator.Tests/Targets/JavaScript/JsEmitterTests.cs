        await Assert.That(run.File("Item.d.ts")).Contains("hashKey_: string | null;");
    }

    private static string MoneySource(string spec) => TargetTestRunner.Usings + """
        #nullable enable
        [assembly: NexusFormatter<Demo.MoneyFormatter, Demo.Money>]
        [assembly: NexusTargetFormatter<Demo.Money>(NexusTargets.JavaScript, "SPEC")]

        namespace Demo;

        public readonly record struct Money(long Cents);

        public sealed class MoneyFormatter : NexusFormatter<Money>
        {
            public override void Serialize(ref MsgPackWriter writer, Money value) => writer.Write(value.Cents);
            public override void Deserialize(ref MsgPackReader reader, ref Money value) => value = new Money(reader.ReadInt64());
        }

        public interface IClientNexus { ValueTask Notify(string message); }
        public interface IServerNexus { ValueTask<Money> Get(); }

        [Nexus<IClientNexus, IServerNexus>(NexusType = NexusType.Client)]
        public partial class ClientNexus { }

        [Nexus<IServerNexus, IClientNexus>(NexusType = NexusType.Server, Targets = NexusTargets.JavaScript)]
        public partial class ServerNexus { }
        """.Replace("SPEC", spec);

    private static string Source(string types, string itemType) => TargetTestRunner.Usings + """
        #nullable enable
        namespace Demo;

        """ + types + """

        public interface IClientNexus { ValueTask Notify(string message); }
        public interface IServerNexus { ValueTask<ITEM> Get(); }

        [Nexus<IClientNexus, IServerNexus>(NexusType = NexusType.Client)]
        public partial class ClientNexus { }

        [Nexus<IServerNexus, IClientNexus>(NexusType = NexusType.Server, Targets = NexusTargets.JavaScript)]
        public partial class ServerNexus { }
        """.Replace("ITEM", itemType);
