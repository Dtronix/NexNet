    [Test]
    public async Task ObjectsAreClassesWithInitAndStructuralEquality()
    {
        var item = Zoo.File("InteropItem.js");
        await Assert.That(item).Contains("export class InteropItem {");
        await Assert.That(item).Contains("constructor(init) {");
        await Assert.That(item).Contains("this.id = init?.id === undefined ? 0 : init.id;");
        await Assert.That(item).Contains("equals(other) {");
        await Assert.That(item).Contains("return $key(['InteropItem', this.id, this.name]);");

        var dts = Zoo.File("InteropItem.d.ts");
        await Assert.That(dts).Contains("export declare class InteropItem {");
        await Assert.That(dts).Contains("constructor(init?: InteropItem.Init);");
        await Assert.That(dts).Contains("name: string | null;");
        await Assert.That(dts).Contains("interface Init {");

        // Bases are extended; members of the base are declared there.
        await Assert.That(Features.File("BigCircle.js")).Contains("export class BigCircle extends Circle {");
        await Assert.That(Features.File("BigCircle.js")).Contains("super(init);");
        await Assert.That(Features.File("BigCircle.js")).DoesNotContain("this.radius =");
        await Assert.That(Features.File("BigCircle.d.ts")).Contains("interface Init extends Circle.Init {");
        await Assert.That(Features.File("Circle.js")).Contains("export class Circle extends Shape {");
        await Assert.That(Features.File("Holder.d.ts")).Contains("export declare class Holder<T> {");
        await Assert.That(Features.File("Holder.d.ts")).Contains("constructor(init?: Holder.Init<T>);");
    }

    [Test]
    public async Task MembersStartAtTheirCSharpInitialValue()
    {
        var defaults = Features.File("Defaults.js");
        await Assert.That(defaults).Contains("this.count = init?.count === undefined ? 5 : init.count;");
        await Assert.That(defaults).Contains("this.name = init?.name === undefined ? 'a\"b\\\\c\\n\\" + "u00e9' : init.name;");
        await Assert.That(defaults).Contains("this.single = init?.single === undefined ? 2.25 : init.single;");
        await Assert.That(defaults).Contains("this.price = init?.price === undefined ? $rt.NexusDecimal.parse('1.25') : init.price;");
        await Assert.That(defaults).Contains("this.mode = init?.mode === undefined ? Small.B : init.mode;");
        await Assert.That(defaults).Contains("this.unsigned = init?.unsigned === undefined ? 18446744073709551615n : init.unsigned;");
        await Assert.That(defaults).Contains("import { Small } from './Small.js';");

        // C# value types start at default(T), as C# writes them.
        await Assert.That(defaults).Contains("this.when = init?.when === undefined ? new $rt.NexusDateTime(0n) : init.when;");
        await Assert.That(defaults).Contains("this.pair = init?.pair === undefined ? [0, null] : init.pair;");
        await Assert.That(defaults).Contains("this.memory = init?.memory === undefined ? new Int32Array(0) : init.memory;");
        await Assert.That(defaults).Contains("this.id = init?.id === undefined ? '00000000-0000-0000-0000-000000000000' : init.id;");
        await Assert.That(Features.File("Everything.js")).Contains("this.spot = init?.spot === undefined ? new Spot() : init.spot;");
        await Assert.That(Features.File("Everything.js")).Contains("this.huge = init?.huge === undefined ? 0n : init.huge;");
    }

    [Test]
    public async Task EnumsAreFrozenConstantsAndALiteralType()
    {
        var neg = Features.File("Neg.js");
        await Assert.That(neg).Contains("export const Neg = Object.freeze({");
        await Assert.That(neg).Contains("M: -128,");
        await Assert.That(Features.File("Neg.d.ts")).Contains("export type Neg = -128 | 0 | 127;");

        // 64-bit enums are bigint; UInt64 values are unsigned.
        await Assert.That(Features.File("Huge.js")).Contains("Max: 18446744073709551615n,");
        await Assert.That(Features.File("Huge.d.ts")).Contains("export type Huge = 0n | 9223372036854775808n | 18446744073709551615n;");

        // Flags combine: any value of the underlying type.
        await Assert.That(Features.File("Small.d.ts")).Contains("export type Small = number;");
        await Assert.That(Features.File("Wide.d.ts")).Contains("export type Wide = bigint;");
    }

