    private static JsRun? _zoo;
    private static JsRun? _features;

    internal static JsRun Zoo => _zoo ??= JsTestRunner.Run(JsFixtures.Zoo());

    internal static JsRun Features => _features ??= JsTestRunner.Run(JsFixtures.Features);

    private static async Task AssertClean(JsRun run)
    {
        await Assert.That(run.Ir).IsNotNull();
        await Assert.That(run.Diagnostics.Select(d => d.ToString())).IsEmpty();
        await Assert.That(run.CompileErrors.Select(d => d.ToString())).IsEmpty();
    }

    // ------------------------------------------------------------------ snapshots

    [Test]
    public async Task ZooRunsClean() => await AssertClean(Zoo);

    [Test]
    public async Task FeaturesRunClean() => await AssertClean(Features);

    [Test]
    public Task ZooSnapshot() => JsSnapshots.Verify("zoo", Zoo.Concatenated());

    [Test]
    public Task FeaturesSnapshot() => JsSnapshots.Verify("features", Features.Concatenated());

    // ------------------------------------------------------------------ layout

    [Test]
    public async Task OneModuleAndDeclarationsPerType_PlusFormattersAndSupport()
    {
        var options = JsTestRunner.TargetOptionsFor();
        var expected = Features.Ir!.Types
            .SelectMany(t => JavaScriptTarget.Instance.TypeFiles(t, options))
            .Concat(new[] { "formatters.js", "formatters.d.ts", "nexnet-support.js", "nexnet-support.d.ts", "user-formatters.d.ts" })
            .OrderBy(p => p, StringComparer.Ordinal)
            .ToArray();

        await Assert.That(Features.Files.Keys.OrderBy(p => p, StringComparer.Ordinal)).IsEquivalentTo(expected);
        await Assert.That(Features.Files.Keys).Contains("Outer_Inner.js");
        foreach (var (_, content) in Features.Files)
            await Assert.That(content).StartsWith(JsSyntax.Header + "\n");
    }

    [Test]
    public async Task HeaderNamesTheGeneratorVersion()
    {
        var version = typeof(JsSyntax).Assembly.GetName().Version!;
        await Assert.That(JsSyntax.Header).StartsWith("// <auto-generated> NexNet " + version.Major + "." + version.Minor + "." + version.Build + " ");
    }

