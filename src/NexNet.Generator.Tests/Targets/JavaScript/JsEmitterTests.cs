        });
    }

    [Test]
    public async Task ExpressionsForProxies()
    {
        // J04 builds argument formatters with the same builder, through its import of the formatter module.
        var expressions = new JsFormatterExpressions(new TypeScope(Features.Ir!), "fmt.", spec => "user");
        var list = new TypeRef(TypeRefKind.Seq) { Clr = "List", Args = new(new[] { new TypeRef(TypeRefKind.Decl) { DeclId = "Feat.Defaults" } }) };
        await Assert.That(expressions.For(list)).IsEqualTo("$rt.arrayFormatter(fmt.DefaultsFormatter)");
        var map = new TypeRef(TypeRefKind.Map)
        {
            Args = new(new[]
            {
                new TypeRef(TypeRefKind.Prim) { Prim = PrimKind.String },
                new TypeRef(TypeRefKind.Nullable) { Args = new(new[] { new TypeRef(TypeRefKind.Prim) { Prim = PrimKind.Int64 } }) },
            }),
        };
        await Assert.That(expressions.For(map)).IsEqualTo("$rt.mapFormatter($rt.stringFormatter, $rt.nullableFormatter($rt.int64Formatter))");
    }

