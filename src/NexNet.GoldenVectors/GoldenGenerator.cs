using System.Text;
using NexNet.Interop;
using NexNet.TestNexus.Interop;

[assembly: NexusTestScaffolding<IInteropServerNexus, IInteropClientNexus>]

namespace NexNet.GoldenVectors;

/// <summary>
/// Generates the golden vector files. The output depends only on this code and the NexNet implementation: no time,
/// randomness, culture, time zone or path goes into it.
/// </summary>
public static partial class GoldenGenerator
{
    /// <summary>The vector files, in order. Each is <c>&lt;name&gt;.jsonl</c>.</summary>
    public static readonly IReadOnlyList<string> Files =
        ["primitives", "containers", "ext78", "objects", "unions", "messages", "frames", "collections", GoldenBuilder.RejectFile];

    /// <summary>The file of the declared types.</summary>
    public const string SchemaFile = "schemas.jsonl";

    /// <summary>The fuzz seed corpus file, relative to the repository root.</summary>
    public static readonly string CorpusPath = Path.Combine("src", "NexNet.Fuzz", "Corpus", "golden.hex");

    /// <summary>
    /// The declared types: the interop zoo as the generator describes it, externals, message bodies and the
    /// collection-sync item union.
    /// </summary>
    public static GoldenSchemas CreateSchemas()
        => GoldenSchemas.Create(
            TypedCodecs.Get<InteropAllTypes>().Schemas,
            [("InteropPoint", "User formatter InteropPointFormatter: [X: int, Y: int], two canonical integers.")],
            Messages().Concat(CollectionMessages()),
            IsZooStruct,
            CollectionUnions());

    /// <summary>True when the zoo type with full metadata name <paramref name="fullName"/> is a C# struct.</summary>
    private static bool IsZooStruct(string fullName)
        => (typeof(InteropAllTypes).Assembly.GetType(fullName, throwOnError: false)
            ?? throw new InvalidOperationException("Zoo type " + fullName + " is not in " + typeof(InteropAllTypes).Assembly.GetName().Name + "."))
            .IsValueType;

    /// <summary>Builds every vector, checking each against the C# implementation.</summary>
    public static GoldenBuilder Build()
    {
        var b = new GoldenBuilder(CreateSchemas());
        Primitives(b);
        Containers(b);
        Ext78(b);
        Objects(b);
        Unions(b);
        MessageVectors(b);
        Frames(b);
        CollectionVectors(b);
        return b;
    }

    /// <summary>The content of every output file by name: the vector files, then <see cref="SchemaFile"/>.</summary>
    public static IReadOnlyList<(string Name, string Content)> Render(GoldenBuilder b)
    {
        var files = new List<(string, string)>();
        foreach (var file in Files)
        {
            var sb = new StringBuilder();
            foreach (var vector in b.Vectors.Where(v => v.File == file))
                sb.Append(GoldenFormat.Write(vector)).Append('\n');
            files.Add((file + ".jsonl", sb.ToString()));
        }

        var schemas = new StringBuilder();
        foreach (var line in b.Schemas.ToJson())
            schemas.Append(GoldenFormat.Canonical(line)).Append('\n');
        files.Add((SchemaFile, schemas.ToString()));
        return files;
    }

    /// <summary>
    /// The fuzz seed corpus: the bytes of every vector up to 4 KiB (one hex value per line), each once, by file.
    /// </summary>
    public static string RenderCorpus(GoldenBuilder b)
    {
        const int maxLength = 4096;
        var sb = new StringBuilder();
        sb.Append("# Seed corpus: the golden vectors of tests/golden (one hex value per line), up to ").Append(maxLength).Append(" bytes each.\n");
        sb.Append("# Generated by src/NexNet.GoldenVectors; do not edit. Regenerate with the command in tests/golden/README.md.\n");
        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var file in Files)
        {
            sb.Append("# ").Append(file).Append(".jsonl\n");
            foreach (var vector in b.Vectors.Where(v => v.File == file))
            {
                if (vector.Hex.Length == 0 || vector.Hex.Length > maxLength)
                    continue;
                var hex = Convert.ToHexStringLower(vector.Hex);
                if (seen.Add(hex))
                    sb.Append(hex).Append('\n');
            }
        }

        return sb.ToString();
    }

    /// <summary>
    /// Writes the vector files to <paramref name="outDirectory"/>, removing vector files it no longer produces, and the
    /// corpus to <paramref name="corpusFile"/> unless it is null. Returns the files written.
    /// </summary>
    public static IReadOnlyList<string> Write(string outDirectory, string? corpusFile)
    {
        var b = Build();
        Directory.CreateDirectory(outDirectory);
        var written = new List<string>();
        var rendered = Render(b);
        foreach (var (name, content) in rendered)
        {
            var path = Path.Combine(outDirectory, name);
            System.IO.File.WriteAllText(path, content, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
            written.Add(path);
        }

        foreach (var stale in Directory.EnumerateFiles(outDirectory, "*.jsonl"))
        {
            if (!rendered.Any(f => f.Name == Path.GetFileName(stale)))
                System.IO.File.Delete(stale);
        }

        if (corpusFile != null)
        {
            System.IO.File.WriteAllText(corpusFile, RenderCorpus(b), new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
            written.Add(corpusFile);
        }

        return written;
    }
}
