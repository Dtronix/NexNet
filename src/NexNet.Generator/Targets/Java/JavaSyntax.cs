using System.Globalization;
using System.Text;

namespace NexNet.Generator.Targets.Java;

/// <summary>Java source text helpers shared by the Java emitters: literals, Javadoc and nullness annotations.</summary>
internal static class JavaSyntax
{
    /// <summary>First line of every generated Java file.</summary>
    public const string Header = "// <auto-generated/> Generated by the NexNet generator (Java target). Do not edit.";

    /// <summary>The JSpecify nullness annotation, imported by every file that uses it.</summary>
    public const string NullableImport = "import org.jspecify.annotations.Nullable;";

    /// <summary>The runtime's built-in formatters, always referenced fully qualified (the generated class has the same simple name).</summary>
    public const string RuntimeFormatters = "com.dtronix.nexnet.serialization.Formatters";

    /// <summary>
    /// The type with a JSpecify &lt;c&gt;@Nullable&lt;/c&gt; (a type-use annotation) where Java allows it: before the simple name of a
    /// qualified type (&lt;c&gt;java.util.@Nullable List&amp;lt;T&amp;gt;&lt;/c&gt;), before the brackets of an array
    /// (&lt;c&gt;byte @Nullable []&lt;/c&gt;), otherwise in front. Primitive types are returned unchanged.
    /// </summary>
    public static string Nullable(string type)
    {
        if (IsPrimitive(type))
            return type;

        if (type.EndsWith("[]", StringComparison.Ordinal))
            return type.Substring(0, type.Length - 2) + " @Nullable []";

        var generic = type.IndexOf('<');
        var head = generic < 0 ? type : type.Substring(0, generic);
        var dot = head.LastIndexOf('.');
        return dot < 0 ? "@Nullable " + type : type.Substring(0, dot + 1) + "@Nullable " + type.Substring(dot + 1);
    }

    /// <summary>True for the eight Java primitive types.</summary>
    public static bool IsPrimitive(string type) => type is "boolean" or "byte" or "short" or "int" or "long" or "float" or "double" or "char";

    /// <summary>The zero value of a Java type: &lt;c&gt;0&lt;/c&gt;, &lt;c&gt;false&lt;/c&gt;… for primitives, &lt;c&gt;null&lt;/c&gt; otherwise.</summary>
    public static string Zero(string type) => type switch
    {
        "boolean" => "false",
        "byte" => "(byte) 0",
        "short" => "(short) 0",
        "int" => "0",
        "long" => "0L",
        "float" => "0f",
        "double" => "0d",
        "char" => "'\\0'",
        _ => "null",
    };

    /// <summary>The name with its first letter in upper case (&lt;c&gt;name&lt;/c&gt; → &lt;c&gt;Name&lt;/c&gt;), for accessor names.</summary>
    public static string UpperFirst(string name)
        => name.Length == 0 || char.IsUpper(name[0]) ? name : char.ToUpperInvariant(name[0]) + name.Substring(1);

    /// <summary>An int literal.</summary>
    public static string Int(long value) => value.ToString(CultureInfo.InvariantCulture);

    /// <summary>A Java string literal. Line terminators and other controls use octal or short escapes, never \u escapes, which javac would translate before lexing.</summary>
    public static string StringLiteral(string value)
    {
        var sb = new StringBuilder(value.Length + 2).Append('"');
        foreach (var c in value)
            AppendEscaped(sb, c, '"');
        return sb.Append('"').ToString();
    }

    /// <summary>A Java char literal.</summary>
    public static string CharLiteral(char value)
    {
        var sb = new StringBuilder(8).Append('\'');
        AppendEscaped(sb, value, '\'');
        return sb.Append('\'').ToString();
    }

    private static void AppendEscaped(StringBuilder sb, char c, char quote)
    {
        switch (c)
        {
            case '\\': sb.Append("\\\\"); return;
            case '\n': sb.Append("\\n"); return;
            case '\r': sb.Append("\\r"); return;
            case '\t': sb.Append("\\t"); return;
            case '\b': sb.Append("\\b"); return;
            case '\f': sb.Append("\\f"); return;
        }

        if (c == quote)
            sb.Append('\\').Append(c);
        else if (c < 0x20 || c == 0x7f)
            sb.Append('\\').Append(Convert.ToString(c, 8).PadLeft(3, '0'));
        else if (c > 0x7e)
            sb.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
        else
            sb.Append(c);
    }

    /// <summary>
    /// Text for a Javadoc comment: HTML-escaped, with the characters javac or Javadoc would interpret (&lt;c&gt;*/&lt;/c&gt;,
    /// &lt;c&gt;@&lt;/c&gt;, &lt;c&gt;{&lt;/c&gt;, backslash) written as entities.
    /// </summary>
    public static string DocText(string text)
    {
        var sb = new StringBuilder(text.Length);
        foreach (var c in text)
        {
            switch (c)
            {
                case '&': sb.Append("&amp;"); break;
                case '<': sb.Append("&lt;"); break;
                case '>': sb.Append("&gt;"); break;
                case '@': sb.Append("&#64;"); break;
                case '{': sb.Append("&#123;"); break;
                case '}': sb.Append("&#125;"); break;
                case '\\': sb.Append("&#92;"); break;
                case '/' when sb.Length > 0 && sb[sb.Length - 1] == '*': sb.Append("&#47;"); break;
                case '\r':
                case '\n':
                case '\t':
                    sb.Append(' ');
                    break;
                default:
                    if (c < 0x20)
                        break;
                    if (c > 0x7e)
                        sb.Append("&#").Append(((int)c).ToString(CultureInfo.InvariantCulture)).Append(';');
                    else
                        sb.Append(c);
                    break;
            }
        }

        return sb.ToString();
    }

    /// <summary>
    /// Writes a Javadoc comment: the summary (already escaped with &lt;see cref="DocText"/&gt; or literal markup), then any
    /// block tags. Nothing is written when both are empty.
    /// </summary>
    public static void Javadoc(CodeWriter w, string? summary, params string[] tags)
    {
        var hasSummary = !string.IsNullOrWhiteSpace(summary);
        if (!hasSummary && tags.Length == 0)
            return;

        if (hasSummary && tags.Length == 0)
        {
            w.Line("/** " + summary + " */");
            return;
        }

        w.Line("/**");
        if (hasSummary)
        {
            w.Line(" * " + summary);
            if (tags.Length > 0)
                w.Line(" *");
        }

        foreach (var tag in tags)
            w.Line(tag.Length == 0 ? " *" : " * " + tag);
        w.Line(" */");
    }

    /// <summary>The escaped IR documentation, or the fallback when there is none.</summary>
    public static string Doc(string? irDocs, string fallback) => string.IsNullOrWhiteSpace(irDocs) ? fallback : DocText(irDocs!.Trim());
}
