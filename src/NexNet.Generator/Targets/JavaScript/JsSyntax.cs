using System.Globalization;
using System.Text;

namespace NexNet.Generator.Targets.JavaScript;

/// <summary>JavaScript and TypeScript source text helpers shared by the JavaScript emitters.</summary>
internal static class JsSyntax
{
    /// <summary>The runtime module namespace every generated module imports (<c>import * as $rt from '…'</c>).</summary>
    public const string Rt = "$rt";

    /// <summary>The module generated code imports the runtime from when <c>ModuleName</c> is not set.</summary>
    public const string DefaultRuntimeModule = "@dtronix/nexnet";

    /// <summary>The generated support module (structural equality and hash keys).</summary>
    public const string SupportModule = "nexnet-support";

    /// <summary>The generated formatter module.</summary>
    public const string FormattersModule = "formatters";

    /// <summary>The generated declarations of the user formatters (D12).</summary>
    public const string UserFormattersModule = "user-formatters";

    /// <summary>First line of every generated file: <c>// &lt;auto-generated&gt; NexNet 0.20.0</c>.</summary>
    public static string Header { get; } = "// <auto-generated> NexNet " + GeneratorVersion() + " (JavaScript target). Do not edit.";

    private static string GeneratorVersion()
    {
        var version = typeof(JsSyntax).Assembly.GetName().Version;
        return version == null
            ? "0.0.0"
            : version.Major.ToString(CultureInfo.InvariantCulture) + "." + version.Minor.ToString(CultureInfo.InvariantCulture) + "."
              + Math.Max(0, version.Build).ToString(CultureInfo.InvariantCulture);
    }

    /// <summary>An integer literal.</summary>
    public static string Int(long value) => value.ToString(CultureInfo.InvariantCulture);

    /// <summary>
    /// A single-quoted string literal. Everything outside printable ASCII is escaped, so the output is plain ASCII;
    /// lone surrogates are kept as <c>\uXXXX</c>.
    /// </summary>
    public static string String(string value)
    {
        var sb = new StringBuilder(value.Length + 2);
        sb.Append('\'');
        foreach (var c in value)
        {
            switch (c)
            {
                case '\\':
                    sb.Append("\\\\");
                    break;
                case '\'':
                    sb.Append("\\'");
                    break;
                case '\n':
                    sb.Append("\\n");
                    break;
                case '\r':
                    sb.Append("\\r");
                    break;
                case '\t':
                    sb.Append("\\t");
                    break;
                default:
                    if (c < 0x20 || c > 0x7e)
                        sb.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                    else
                        sb.Append(c);
                    break;
            }
        }

        return sb.Append('\'').ToString();
    }

    /// <summary>True when the text is a plain identifier (ASCII letters, digits, '_' and '$', not starting with a digit).</summary>
    public static bool IsIdentifier(string text)
    {
        if (text.Length == 0 || char.IsDigit(text[0]))
            return false;
        foreach (var c in text)
        {
            if (!((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '_' || c == '$'))
                return false;
        }

        return true;
    }

    /// <summary>Text safe inside a <c>/** … */</c> comment: no comment terminator, one line per line.</summary>
    public static string DocText(string text) => text.Replace("*/", "*\\/").Replace("\r\n", "\n").Replace('\r', '\n');

    /// <summary>Writes a JSDoc/TSDoc block from the paragraphs (null and empty entries are skipped).</summary>
    public static void Doc(CodeWriter w, params string?[] paragraphs)
    {
        var lines = new List<string>();
        foreach (var paragraph in paragraphs)
        {
            if (string.IsNullOrEmpty(paragraph))
                continue;
            if (lines.Count > 0)
                lines.Add("");
            lines.AddRange(DocText(paragraph!.Trim()).Split('\n').Select(l => l.TrimEnd()));
        }

        if (lines.Count == 0)
            return;
        if (lines.Count == 1)
        {
            w.Line("/** " + lines[0] + " */");
            return;
        }

        w.Line("/**");
        foreach (var line in lines)
            w.Line(line.Length == 0 ? " *" : " * " + line);
        w.Line(" */");
    }

    /// <summary>Inline code in a doc comment: <c>`text`</c>.</summary>
    public static string Code(string text) => "`" + text.Replace("`", "'") + "`";
}
