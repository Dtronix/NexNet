using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using NexNet.Generator.Extraction;
using NexNet.Generator.Ir;
using NexNet.Generator.Models;
using NexNet.Generator.Validation;

namespace NexNet.Generator.Emission;

/// <summary>The inspector schema file of one nexus class: its hint name and source.</summary>
internal sealed record InspectorSchemaOutput(string HintName, string Source);

/// <summary>
/// The opt-in inspector schema (MSBuild property <c>NexNetEmitInspectorSchema</c>): the nexus pair's IR as MessagePack
/// (<see cref="IrMsgPack"/>), emitted as an explicit <c>NexNet.Diagnostics.IInspectorSchemaSource</c> implementation in
/// its own file, so the nexus file is unchanged whether the property is on or off.
/// </summary>
internal static class InspectorSchemaEmitter
{
    /// <summary>The compiler-visible MSBuild property that turns the schema on.</summary>
    public const string Property = "build_property.NexNetEmitInspectorSchema";

    private const int BytesPerLine = 24;

    /// <summary>True when the global options set <see cref="Property"/> to <c>true</c>.</summary>
    public static bool IsEnabled(AnalyzerConfigOptions options)
        => options.TryGetValue(Property, out var value)
           && string.Equals(value.Trim(), "true", StringComparison.OrdinalIgnoreCase);

    /// <summary>
    /// The schema file of the nexus class <paramref name="data"/> was extracted from, or null when the nexus is not
    /// generated (the same blocking diagnostics as the nexus file) or has no export.
    /// </summary>
    public static InspectorSchemaOutput? Build(NexusGenerationData data, Compilation compilation, CancellationToken cancellationToken)
    {
        if (IsBlocked(data, cancellationToken))
            return null;

        // The validator rejects nested and generic nexus classes, so namespace + name is the metadata name.
        if (compilation.GetTypeByMetadataName(data.Namespace + "." + data.TypeName) is not { } symbol)
            return null;

        var ir = IrBuilder.Merge(new[] { IrBuilder.Build(compilation, symbol, data, cancellationToken) });
        if (ir.Exports.Length == 0)
            return null;

        var bytes = IrMsgPack.Write(ir);
        return new InspectorSchemaOutput(data.FullTypeName + ".InspectorSchema.g.cs", Emit(data, bytes, IrMsgPack.Hash(bytes)));
    }

    // Mirrors NexusGenerator.Generate: no schema for a nexus whose own code is not generated, so the partial class is
    // never left implementing an interface on a type that does not otherwise exist. NEXNET042 leaves no export to build.
    private static bool IsBlocked(NexusGenerationData data, CancellationToken cancellationToken)
    {
        if (NexusDataExtractor.HasDuplicateMethodNames(data.NexusInterface.AllMethods)
            || NexusDataExtractor.HasDuplicateMethodNames(data.ProxyInterface.AllMethods))
            return true;

        if (data.SerializationDiagnostics.Any(d => d.Id != "NEXNET037"))
            return true;

        return NexusValidator.Validate(data, cancellationToken).Any(d =>
            d.Severity == DiagnosticSeverity.Error && d.Id != DiagnosticDescriptors.VersionHashLockMismatch.Id);
    }

    /// <summary>The generated source for <paramref name="bytes"/> on the nexus class of <paramref name="data"/>.</summary>
    internal static string Emit(NexusGenerationData data, byte[] bytes, ulong hash)
    {
        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n#nullable enable\n\nnamespace ").Append(data.Namespace).Append("\n{\n");
        sb.Append("    partial class ").Append(data.TypeName).Append(" : global::NexNet.Diagnostics.IInspectorSchemaSource\n    {\n");

        // A constant byte array converted to ReadOnlySpan<byte> is stored in the data section: no allocation per read.
        sb.Append("        static global::System.ReadOnlySpan<byte> global::NexNet.Diagnostics.IInspectorSchemaSource.InspectorSchema => new byte[]\n        {\n");
        for (var i = 0; i < bytes.Length; i += BytesPerLine)
        {
            sb.Append("           ");
            var end = Math.Min(i + BytesPerLine, bytes.Length);
            for (var j = i; j < end; j++)
                sb.Append(" 0x").Append(bytes[j].ToString("X2", CultureInfo.InvariantCulture)).Append(',');
            sb.Append('\n');
        }

        sb.Append("        };\n\n");
        sb.Append("        static ulong global::NexNet.Diagnostics.IInspectorSchemaSource.InspectorSchemaHash => 0x")
            .Append(hash.ToString("X16", CultureInfo.InvariantCulture)).Append("UL;\n");
        sb.Append("    }\n}\n");
        return sb.ToString();
    }
}
