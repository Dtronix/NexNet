// MSBuild inline tasks of NexNet.Generator.targets, compiled by RoslynCodeTaskFactory (netstandard, no NexNet
// references). Not part of the generator assembly. The bundle format is documented in
// src/NexNet.Generator/Bundle/TargetBundle.cs; this parser must stay in step with it.
using System;
using System.Collections;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using Microsoft.Build.Framework;
using Microsoft.Build.Utilities;

/// <summary>
/// Flattens NexNetTarget items into the generator's configuration: <c>TargetIds</c> (ids with an OutputDir) and one
/// <c>NexNetTarget_&lt;id&gt;_&lt;Metadata&gt;</c> item per other non-blank metadata, with its value in <c>Value</c>.
/// </summary>
public class NexNetFlattenTargets : Task
{
    [Required]
    public ITaskItem[] Targets { get; set; }

    [Output]
    public string TargetIds { get; set; }

    [Output]
    public ITaskItem[] Options { get; set; }

    public override bool Execute()
    {
        var ids = new List<string>();
        var seen = new HashSet<string>(StringComparer.Ordinal);
        var options = new List<ITaskItem>();

        foreach (var target in Targets ?? new ITaskItem[0])
        {
            var id = target.ItemSpec.Trim().ToLowerInvariant();
            if (id.Length == 0)
                continue;
            if (!seen.Add(id))
            {
                Log.LogWarning(null, "NEXNETB005", null, null, 0, 0, 0, 0,
                    "NexNetTarget '{0}' is declared more than once; only the first declaration is used.", id);
                continue;
            }

            // A target without an output directory is not listed; the generator then reports NEXNET044 for exports
            // that opt in to it.
            if (!string.IsNullOrWhiteSpace(target.GetMetadata("OutputDir")))
                ids.Add(id);

            foreach (DictionaryEntry entry in target.CloneCustomMetadata())
            {
                var name = (string)entry.Key;
                var value = (string)entry.Value;
                if (string.Equals(name, "OutputDir", StringComparison.OrdinalIgnoreCase) || string.IsNullOrWhiteSpace(value))
                    continue;

                var option = new TaskItem("NexNetTarget_" + id + "_" + name);
                option.SetMetadata("Value", value.Trim());
                options.Add(option);
            }
        }

        // ',' not ';': the .editorconfig parser reads ';' as the start of a comment.
        TargetIds = string.Join(",", ids);
        Options = options.OrderBy(o => o.ItemSpec, StringComparer.Ordinal).ToArray();
        return true;
    }
}

/// <summary>
/// Writes the files of a NexNet target bundle to disk, and deletes files of the previous unpack that are gone.
/// Without <c>BundleFile</c> it deletes every file of the manifest (Clean).
/// </summary>
public class NexNetUnpackBundle : Task
{
    private const string Header = "// <auto-generated/> NexNet target bundle v1";
    private const string HeaderPrefix = "// <auto-generated/> NexNet target bundle v";
    private const string FilePrefix = "// @file ";
    private const string HashMarker = " sha256=";
    private const string LinePrefix = "// ";
    private const string IrFileName = "nexnet-ir.json";

    private static readonly bool CaseInsensitive = Path.DirectorySeparatorChar == '\\';
    private static readonly StringComparer PathComparer = CaseInsensitive ? StringComparer.OrdinalIgnoreCase : StringComparer.Ordinal;
    private static readonly StringComparison PathComparison = CaseInsensitive ? StringComparison.OrdinalIgnoreCase : StringComparison.Ordinal;

    /// <summary>The bundle (NexNet.Targets.g.cs). Empty: clean.</summary>
    public string BundleFile { get; set; }

    /// <summary>The NexNetTarget items (OutputDir metadata).</summary>
    public ITaskItem[] Targets { get; set; }

    [Required]
    public string ProjectDirectory { get; set; }

    /// <summary>Where nexnet-ir.json goes.</summary>
    public string IrOutputPath { get; set; }

    [Required]
    public string ManifestFile { get; set; }

    private sealed class Entry
    {
        public string Root;
        public string Path;
        public byte[] Bytes;
    }

    public override bool Execute()
    {
        var manifestPath = Full(ManifestFile);
        var previous = ReadManifest(manifestPath);

        if (string.IsNullOrEmpty(BundleFile))
        {
            var removed = DeleteAll(previous, new HashSet<string>(PathComparer));
            TryDelete(manifestPath);
            Log.LogMessage(MessageImportance.Normal, "NexNet: removed {0} generated target file(s).", removed);
            return !Log.HasLoggedErrors;
        }

        var entries = Parse();
        if (entries == null || Log.HasLoggedErrors)
            return false;

        int written = 0, unchanged = 0;
        foreach (var entry in entries)
        {
            if (File.Exists(entry.Path) && SameBytes(entry.Path, entry.Bytes))
            {
                unchanged++;
                continue;
            }

            if (WriteAtomic(entry.Path, entry.Bytes))
                written++;
        }

        var current = new HashSet<string>(entries.Select(e => e.Path), PathComparer);
        var deleted = DeleteAll(previous, current);

        WriteManifest(manifestPath, entries);
        Log.LogMessage(written + deleted > 0 ? MessageImportance.High : MessageImportance.Normal,
            "NexNet: {0} target file(s) written, {1} unchanged, {2} deleted.", written, unchanged, deleted);
        return !Log.HasLoggedErrors;
    }

    private string Full(string path) => Path.GetFullPath(Path.Combine(ProjectDirectory, path));

    /// <summary>The bundle's files with their destination, or null after logging an error. Writes nothing.</summary>
    private List<Entry> Parse()
    {
        string text;
        try
        {
            text = File.ReadAllText(BundleFile, new UTF8Encoding(false));
        }
        catch (Exception ex) when (ex is IOException || ex is UnauthorizedAccessException)
        {
            Log.LogError(null, "NEXNETB004", null, BundleFile, 0, 0, 0, 0, "Cannot read the NexNet target bundle: {0}", ex.Message);
            return null;
        }

        var lines = text.Replace("\r\n", "\n").Split('\n');
        if (lines.Length == 0 || lines[0] != Header)
        {
            var found = lines.Length > 0 && lines[0].StartsWith(HeaderPrefix, StringComparison.Ordinal) ? lines[0].Substring(HeaderPrefix.Length - 1) : "none";
            Log.LogError(null, "NEXNETB002", null, BundleFile, 1, 0, 0, 0,
                "Unsupported NexNet target bundle (version {0}); this unpack target reads v1. NexNet.Generator and its build files must come from the same package.", found);
            return null;
        }

        var roots = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var target in Targets ?? new ITaskItem[0])
        {
            var id = target.ItemSpec.Trim();
            var outputDir = target.GetMetadata("OutputDir");
            if (id.Length == 0 || string.IsNullOrWhiteSpace(outputDir) || roots.ContainsKey(id))
                continue;
            roots[id] = TrimSeparator(Full(outputDir.Trim()));
        }

        var entries = new List<Entry>();
        var destinations = new HashSet<string>(PathComparer);
        string path = null, hash = null;
        int headerLine = 0;
        var base64 = new StringBuilder();

        bool Flush()
        {
            if (path == null)
                return true;

            byte[] bytes;
            try
            {
                bytes = Convert.FromBase64String(base64.ToString());
            }
            catch (FormatException)
            {
                return Corrupt(headerLine, "the content of '" + path + "' is not valid base64");
            }

            base64.Clear();
            if (!string.Equals(Sha256Hex(bytes), hash, StringComparison.Ordinal))
                return Corrupt(headerLine, "the sha256 of '" + path + "' does not match its content");

            var entry = Resolve(path, roots, headerLine);
            if (entry == null)
                return false;
            if (!destinations.Add(entry.Path))
                return Corrupt(headerLine, "two files are written to '" + entry.Path + "'");

            entry.Bytes = bytes;
            entries.Add(entry);
            return true;
        }

        for (var i = 1; i < lines.Length; i++)
        {
            var line = lines[i];
            if (line.Length == 0)
                continue;

            if (line.StartsWith(FilePrefix, StringComparison.Ordinal))
            {
                if (!Flush())
                    return null;

                var marker = line.LastIndexOf(HashMarker, StringComparison.Ordinal);
                if (marker < FilePrefix.Length)
                {
                    Corrupt(i + 1, "a file header has no sha256");
                    return null;
                }

                path = line.Substring(FilePrefix.Length, marker - FilePrefix.Length);
                hash = line.Substring(marker + HashMarker.Length);
                headerLine = i + 1;
            }
            else if (path != null && line.StartsWith(LinePrefix, StringComparison.Ordinal))
            {
                base64.Append(line, LinePrefix.Length, line.Length - LinePrefix.Length);
            }
            else
            {
                Corrupt(i + 1, "the line is not part of a file");
                return null;
            }
        }

        return Flush() ? entries : null;
    }

    private Entry Resolve(string path, Dictionary<string, string> roots, int line)
    {
        var segments = path.Split('/');
        if (path.IndexOf('\\') >= 0 || path.IndexOf(':') >= 0 || segments.Any(s => s.Length == 0 || s == "." || s == ".."))
        {
            Corrupt(line, "'" + path + "' is not a relative '/' separated path");
            return null;
        }

        if (segments.Length == 1)
        {
            if (!string.Equals(path, IrFileName, StringComparison.Ordinal) || string.IsNullOrWhiteSpace(IrOutputPath))
            {
                Corrupt(line, "'" + path + "' belongs to no target");
                return null;
            }

            var irPath = Full(IrOutputPath);
            return new Entry { Root = TrimSeparator(Path.GetDirectoryName(irPath)), Path = irPath };
        }

        if (!roots.TryGetValue(segments[0], out var root))
        {
            Log.LogError(null, "NEXNETB003", null, BundleFile, line, 0, 0, 0,
                "The NexNet target bundle has files for target '{0}', which has no NexNetTarget item with an OutputDir.", segments[0]);
            return null;
        }

        var full = Path.GetFullPath(Path.Combine(root, string.Join(Path.DirectorySeparatorChar.ToString(), segments.Skip(1))));
        if (!full.StartsWith(root + Path.DirectorySeparatorChar, PathComparison))
        {
            Corrupt(line, "'" + path + "' resolves outside the target's OutputDir");
            return null;
        }

        return new Entry { Root = root, Path = full };
    }

    private bool Corrupt(int line, string reason)
    {
        Log.LogError(null, "NEXNETB002", null, BundleFile, line, 0, 0, 0,
            "Invalid NexNet target bundle: {0}. Rebuild the project; if it persists, report a NexNet.Generator bug.", reason);
        return false;
    }

    private bool WriteAtomic(string path, byte[] bytes)
    {
        var temp = path + "." + Guid.NewGuid().ToString("N") + ".tmp";
        try
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllBytes(temp, bytes);
            if (File.Exists(path))
            {
                try
                {
                    File.Replace(temp, path, null);
                }
                catch (PlatformNotSupportedException)
                {
                    File.Copy(temp, path, true);
                    File.Delete(temp);
                }
            }
            else
            {
                File.Move(temp, path);
            }

            return true;
        }
        catch (Exception ex) when (ex is IOException || ex is UnauthorizedAccessException)
        {
            TryDelete(temp);
            Log.LogError(null, "NEXNETB004", null, path, 0, 0, 0, 0, "Cannot write the NexNet target file: {0}", ex.Message);
            return false;
        }
    }

    private static bool SameBytes(string path, byte[] bytes)
    {
        try
        {
            var info = new FileInfo(path);
            if (info.Length != bytes.Length)
                return false;
            var existing = File.ReadAllBytes(path);
            for (var i = 0; i < bytes.Length; i++)
            {
                if (existing[i] != bytes[i])
                    return false;
            }

            return true;
        }
        catch (Exception ex) when (ex is IOException || ex is UnauthorizedAccessException)
        {
            return false;
        }
    }

    /// <summary>Deletes the manifest's files that are not in <paramref name="keep"/>, then their emptied directories.</summary>
    private int DeleteAll(List<KeyValuePair<string, string>> manifest, HashSet<string> keep)
    {
        var deleted = 0;
        foreach (var pair in manifest)
        {
            var root = pair.Key;
            var file = pair.Value;
            if (keep.Contains(file) || !File.Exists(file))
                continue;

            try
            {
                File.Delete(file);
                deleted++;
            }
            catch (Exception ex) when (ex is IOException || ex is UnauthorizedAccessException)
            {
                Log.LogWarning(null, "NEXNETB004", null, file, 0, 0, 0, 0, "Cannot delete the stale NexNet target file: {0}", ex.Message);
                continue;
            }

            // Remove directories the deletion emptied, never the target's OutputDir itself.
            var dir = Path.GetDirectoryName(file);
            while (dir != null && dir.Length > root.Length && dir.StartsWith(root + Path.DirectorySeparatorChar, PathComparison))
            {
                try
                {
                    if (Directory.Exists(dir) && !Directory.EnumerateFileSystemEntries(dir).Any())
                        Directory.Delete(dir);
                    else
                        break;
                }
                catch (Exception ex) when (ex is IOException || ex is UnauthorizedAccessException)
                {
                    break;
                }

                dir = Path.GetDirectoryName(dir);
            }
        }

        return deleted;
    }

    /// <summary>Manifest lines: "R &lt;root&gt;" starts a root; each following "F &lt;file&gt;" is a file under it.</summary>
    private static List<KeyValuePair<string, string>> ReadManifest(string path)
    {
        var result = new List<KeyValuePair<string, string>>();
        if (!File.Exists(path))
            return result;

        string root = null;
        foreach (var line in File.ReadAllLines(path))
        {
            if (line.StartsWith("R ", StringComparison.Ordinal))
                root = line.Substring(2);
            else if (line.StartsWith("F ", StringComparison.Ordinal) && root != null)
                result.Add(new KeyValuePair<string, string>(root, line.Substring(2)));
        }

        return result;
    }

    private void WriteManifest(string path, List<Entry> entries)
    {
        var sb = new StringBuilder();
        sb.Append("# NexNet target files written by the last unpack (deleted when no longer generated, and on Clean).\n");
        foreach (var group in entries.GroupBy(e => e.Root, PathComparer).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            sb.Append("R ").Append(group.Key).Append('\n');
            foreach (var entry in group.OrderBy(e => e.Path, StringComparer.Ordinal))
                sb.Append("F ").Append(entry.Path).Append('\n');
        }

        var bytes = new UTF8Encoding(false).GetBytes(sb.ToString());
        if (File.Exists(path) && SameBytes(path, bytes))
            return;
        WriteAtomic(path, bytes);
    }

    private static string TrimSeparator(string path) => path.TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);

    private static void TryDelete(string path)
    {
        try
        {
            if (File.Exists(path))
                File.Delete(path);
        }
        catch (Exception ex) when (ex is IOException || ex is UnauthorizedAccessException)
        {
        }
    }

    private static string Sha256Hex(byte[] bytes)
    {
        using (var sha = SHA256.Create())
        {
            var hash = sha.ComputeHash(bytes);
            var sb = new StringBuilder(hash.Length * 2);
            foreach (var b in hash)
                sb.Append(b.ToString("x2"));
            return sb.ToString();
        }
    }
}
