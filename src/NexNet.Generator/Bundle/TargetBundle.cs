using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using NexNet.Generator.Targets;

namespace NexNet.Generator.Bundle;

/// <summary>
/// The comment-only target bundle (<c>NexNet.Targets.g.cs</c>): every file the targets emit, carried through the
/// compiler to the MSBuild unpack target (<c>build/NexNet.Generator.targets</c>), which writes them to disk. The
/// generator never does file IO itself (RS1035).
/// </summary>
/// <remarks>
/// Format, version 1 (LF line endings, every line a <c>//</c> comment, so the file compiles to nothing):
/// <code>
/// // &lt;auto-generated/&gt; NexNet target bundle v1
/// // @file java/com/acme/ChatServerProxy.java sha256=&lt;64 lower-case hex digits&gt;
/// // &lt;base64 of the UTF-8 content, at most LineLength characters per line&gt;
/// // @file nexnet-ir.json sha256=&lt;hex&gt;
/// // ...
/// </code>
/// A path is '/' separated and relative. Its first segment is the target id (<c>java</c>, <c>javascript</c>), which the
/// unpack target maps to that target's <c>OutputDir</c>; <see cref="IrFileName"/> has no target segment. The sha256 is
/// of the decoded bytes. An empty file has no base64 lines. The MSBuild task parses this format independently, so a
/// change here is a change of <see cref="Version"/> and of the task.
/// </remarks>
internal static class TargetBundle
{
    /// <summary>Hint name of the bundle source.</summary>
    public const string HintName = "NexNet.Targets.g.cs";

    /// <summary>The bundle format version.</summary>
    public const int Version = 1;

    /// <summary>The first line of a bundle.</summary>
    public static readonly string Header = "// <auto-generated/> NexNet target bundle v" + Version.ToString(CultureInfo.InvariantCulture);

    /// <summary>The IR file every bundle with an IR carries, outside any target directory.</summary>
    public const string IrFileName = "nexnet-ir.json";

    /// <summary>Maximum base64 characters per line (a multiple of 4).</summary>
    public const int LineLength = 100;

    private const string FilePrefix = "// @file ";
    private const string HashMarker = " sha256=";
    private const string LinePrefix = "// ";

    private static readonly UTF8Encoding Utf8 = new(encoderShouldEmitUTF8Identifier: false, throwOnInvalidBytes: true);

    /// <summary>Writes the bundle of <paramref name="files"/>, in the given order.</summary>
    /// <exception cref="ArgumentException">A path is not a valid bundle path, or appears twice.</exception>
    public static string Write(IEnumerable<GeneratedFile> files)
    {
        var sb = new StringBuilder();
        sb.Append(Header).Append('\n');

        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var file in files)
        {
            var problem = ValidatePath(file.Path);
            if (problem != null)
                throw new ArgumentException("Invalid bundle path '" + file.Path + "': " + problem + ".", nameof(files));
            if (!seen.Add(file.Path))
                throw new ArgumentException("The bundle path '" + file.Path + "' appears more than once.", nameof(files));

            var bytes = Utf8.GetBytes(file.Content);
            sb.Append(FilePrefix).Append(file.Path).Append(HashMarker).Append(Sha256Hex(bytes)).Append('\n');

            var base64 = Convert.ToBase64String(bytes);
            for (var i = 0; i < base64.Length; i += LineLength)
                sb.Append(LinePrefix).Append(base64, i, Math.Min(LineLength, base64.Length - i)).Append('\n');
        }

        return sb.ToString();
    }

    /// <summary>Reads a bundle written by <see cref="Write"/> and verifies every hash.</summary>
    /// <exception cref="FormatException">The text is not a valid version-1 bundle, or a hash does not match.</exception>
    public static IReadOnlyList<GeneratedFile> Read(string text)
    {
        var lines = text.Replace("\r\n", "\n").Split('\n');
        if (lines.Length == 0 || lines[0] != Header)
            throw new FormatException("Not a NexNet target bundle v" + Version.ToString(CultureInfo.InvariantCulture) + ".");

        var files = new List<GeneratedFile>();
        string? path = null;
        string? hash = null;
        var base64 = new StringBuilder();

        void Flush()
        {
            if (path == null)
                return;
            var bytes = Convert.FromBase64String(base64.ToString());
            if (!string.Equals(Sha256Hex(bytes), hash, StringComparison.Ordinal))
                throw new FormatException("The sha256 of '" + path + "' does not match its content.");
            files.Add(new GeneratedFile(path, Utf8.GetString(bytes)));
            base64.Clear();
        }

        for (var i = 1; i < lines.Length; i++)
        {
            var line = lines[i];
            if (line.Length == 0)
                continue;

            if (line.StartsWith(FilePrefix, StringComparison.Ordinal))
            {
                Flush();
                var marker = line.LastIndexOf(HashMarker, StringComparison.Ordinal);
                if (marker < FilePrefix.Length)
                    throw new FormatException("Line " + (i + 1).ToString(CultureInfo.InvariantCulture) + ": a file header without sha256.");
                path = line.Substring(FilePrefix.Length, marker - FilePrefix.Length);
                hash = line.Substring(marker + HashMarker.Length);
                var problem = ValidatePath(path);
                if (problem != null)
                    throw new FormatException("Invalid bundle path '" + path + "': " + problem + ".");
            }
            else if (line.StartsWith(LinePrefix, StringComparison.Ordinal) && path != null)
            {
                base64.Append(line, LinePrefix.Length, line.Length - LinePrefix.Length);
            }
            else
            {
                throw new FormatException("Line " + (i + 1).ToString(CultureInfo.InvariantCulture) + " is not part of a bundle file.");
            }
        }

        Flush();
        return files;
    }

    /// <summary>Why <paramref name="path"/> is not a valid bundle path, or null when it is.</summary>
    public static string? ValidatePath(string path)
    {
        if (string.IsNullOrEmpty(path))
            return "it is empty";
        if (path.IndexOf('\\') >= 0)
            return "it contains '\\' (use '/')";
        if (path.StartsWith("/", StringComparison.Ordinal) || path.IndexOf(':') >= 0)
            return "it is not relative";
        foreach (var c in path)
        {
            if (c < ' ' || c == '"' || c == '<' || c == '>' || c == '|' || c == '*' || c == '?')
                return "it contains an invalid character";
        }

        foreach (var segment in path.Split('/'))
        {
            if (segment.Length == 0 || segment == "." || segment == "..")
                return "it has an empty, '.' or '..' segment";
            if (segment.Trim().Length != segment.Length || segment.EndsWith(".", StringComparison.Ordinal))
                return "a segment starts or ends with a space, or ends with '.'";
        }

        return null;
    }

    /// <summary>The lower-case hex sha256 of <paramref name="bytes"/>.</summary>
    public static string Sha256Hex(byte[] bytes)
    {
        using var sha = SHA256.Create();
        var hash = sha.ComputeHash(bytes);
        var sb = new StringBuilder(hash.Length * 2);
        foreach (var b in hash)
            sb.Append(b.ToString("x2", CultureInfo.InvariantCulture));
        return sb.ToString();
    }
}
