using System.Globalization;
using System.Reflection;
using System.Text;
using NexNet.Generator.Targets;

namespace NexNet.Generator.Runtime;

/// <summary>
/// The client runtime sources embedded in the generator (D31, docs/internals/generator-emitted-runtime.md):
/// manifest resources named <c>NexNet.Runtime/&lt;target id&gt;/&lt;path&gt;</c> plus <c>NexNet.Runtime/LICENSE</c>, added by
/// <c>NexNet.Generator.csproj</c> from <c>clients/</c>. Read once per process; every file is LF without a BOM and the files
/// are in ordinal path order, so the emitted runtime is byte-identical on every machine.
/// </summary>
internal static class EmbeddedRuntime
{
    /// <summary>Prefix of every runtime resource name.</summary>
    public const string ResourcePrefix = "NexNet.Runtime/";

    /// <summary>The resource name of the licence text.</summary>
    public const string LicenseResource = ResourcePrefix + "LICENSE";

    /// <summary>Option (<c>NexNetTarget_&lt;id&gt;_EmitRuntime</c>): <c>true</c> emits the client runtime beside the generated code.</summary>
    public const string EmitRuntimeOption = "EmitRuntime";

    private const char ByteOrderMark = (char)0xFEFF;

    private static readonly object Gate = new();
    private static Dictionary<string, IReadOnlyList<GeneratedFile>>? _byTarget;
    private static string? _license;

    /// <summary>The generator version, <c>major.minor.build</c> (lockstep with the NuGet, npm and Java versions).</summary>
    public static string Version { get; } = ReadVersion();

    /// <summary>The licence text (the repository's LICENSE), LF line endings.</summary>
    public static string License
    {
        get
        {
            Load();
            return _license!;
        }
    }

    /// <summary>
    /// The header line every emitted runtime file starts with (<paramref name="comment"/> is the line comment token).
    /// It carries the version, so a generator upgrade rewrites every runtime file.
    /// </summary>
    public static string HeaderLine(string comment)
        => comment + " NexNet client runtime " + Version + ". Generated by NexNet.Generator; do not edit. Copyright (c) 2025 Dtronix. MIT License (see LICENSE).";

    /// <summary>
    /// The embedded runtime sources of a target, paths relative to the runtime source root ('/' separated), in ordinal
    /// order. Empty when the generator was built without them.
    /// </summary>
    public static IReadOnlyList<GeneratedFile> Sources(string targetId)
    {
        Load();
        return _byTarget!.TryGetValue(targetId, out var files) ? files : Array.Empty<GeneratedFile>();
    }

    /// <summary>
    /// Whether a target emits the runtime: the <see cref="EmitRuntimeOption"/> value when set, otherwise
    /// <paramref name="implicitDefault"/>.
    /// </summary>
    public static bool IsEnabled(TargetOptions options, bool implicitDefault)
    {
        var value = options.Get(EmitRuntimeOption);
        return value == null ? implicitDefault : string.Equals(value, "true", StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>Text with LF line endings and no leading BOM.</summary>
    internal static string Normalize(string text)
    {
        if (text.Length > 0 && text[0] == ByteOrderMark)
            text = text.Substring(1);
        return text.Replace("\r\n", "\n").Replace('\r', '\n');
    }

    private static void Load()
    {
        if (_byTarget != null)
            return;

        lock (Gate)
        {
            if (_byTarget != null)
                return;

            var assembly = typeof(EmbeddedRuntime).Assembly;
            var byTarget = new Dictionary<string, List<GeneratedFile>>(StringComparer.Ordinal);
            var license = "";
            foreach (var name in assembly.GetManifestResourceNames())
            {
                // MSBuild's %(RecursiveDir) uses the platform separator.
                var normalized = name.Replace('\\', '/');
                if (!normalized.StartsWith(ResourcePrefix, StringComparison.Ordinal))
                    continue;

                var text = Read(assembly, name);
                if (normalized == LicenseResource)
                {
                    license = text;
                    continue;
                }

                var rest = normalized.Substring(ResourcePrefix.Length);
                var slash = rest.IndexOf('/');
                if (slash <= 0 || slash == rest.Length - 1)
                    continue;

                var target = rest.Substring(0, slash);
                if (!byTarget.TryGetValue(target, out var list))
                    byTarget[target] = list = new List<GeneratedFile>();
                list.Add(new GeneratedFile(rest.Substring(slash + 1), text));
            }

            _license = license;
            _byTarget = byTarget.ToDictionary(
                p => p.Key,
                p => (IReadOnlyList<GeneratedFile>)p.Value.OrderBy(f => f.Path, StringComparer.Ordinal).ToArray(),
                StringComparer.Ordinal);
        }
    }

    private static string Read(Assembly assembly, string name)
    {
        using var stream = assembly.GetManifestResourceStream(name)
            ?? throw new InvalidOperationException("The runtime resource '" + name + "' cannot be read.");
        using var reader = new StreamReader(stream, new UTF8Encoding(false, true), detectEncodingFromByteOrderMarks: true);
        return Normalize(reader.ReadToEnd());
    }

    private static string ReadVersion()
    {
        var version = typeof(EmbeddedRuntime).Assembly.GetName().Version;
        return version == null
            ? "0.0.0"
            : version.Major.ToString(CultureInfo.InvariantCulture) + "." + version.Minor.ToString(CultureInfo.InvariantCulture) + "."
              + Math.Max(0, version.Build).ToString(CultureInfo.InvariantCulture);
    }
}
